export function getBlogPostContent(slug: string, excerpt: string): string {
  const normalized = slug
    .toLowerCase()
    .replace(/ı/g, 'i')
    .replace(/ğ/g, 'g')
    .replace(/ü/g, 'u')
    .replace(/ş/g, 's')
    .replace(/ö/g, 'o')
    .replace(/ç/g, 'c')

  return blogPostContent[normalized] ?? `<p>${excerpt}</p>`
}
